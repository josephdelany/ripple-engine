"""EVALUATION.md sits at the repo root, is machine-generated, and asserted two things the
project's own registered tests contradict: "placebo null (good)" while
`summary.json#/placebo/null_holds` was false, and "H1 holds out-of-sample" for a hypothesis
downgraded under the single evidentiary bar.

A hand-added banner could not fix that: the next `python3 src/evaluate.py` erases it. So the
generator has to read the registered files and emit its own verdict, and this is the test that
holds it to that. It is deliberately written against the GENERATED FILE and the REGISTERED
SOURCES, never against `evaluate.py`'s own arithmetic — the whole defect was a module grading
itself.

Read-only.
"""
import json
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
MD = ROOT / "EVALUATION.md"
JSON_OUT = ROOT / "data" / "evaluation.json"
SUMMARY = ROOT / "data" / "walk_forward" / "summary.json"
BAR = ROOT / "data" / "evidentiary_bar.json"

pytestmark = pytest.mark.skipif(not MD.exists(), reason="EVALUATION.md not generated")


@pytest.fixture(scope="module")
def md():
    return MD.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def registered():
    pl = json.loads(SUMMARY.read_text())["placebo"] if SUMMARY.exists() else {}
    h1 = ((json.loads(BAR.read_text()).get("adjudicated") or {}).get("H1_vix_oil") or {}) if BAR.exists() else {}
    return {"null_holds": pl.get("null_holds"), "legs": h1.get("legs") or {}, "retier": h1.get("retier")}


def test_the_two_retracted_claims_never_appear(md):
    """The exact sentences that were wrong. Named so they cannot come back by a template edit."""
    for banned in ("placebo null (good)", "H1 holds out-of-sample", "holds out-of-sample ✓"):
        assert banned not in md, f"EVALUATION.md asserts a retracted claim: {banned!r}"


def test_the_document_agrees_with_the_registered_placebo(md, registered):
    """If the registered placebo fails, the file must say so before any of its own numbers."""
    nh = registered["null_holds"]
    if nh is False:
        head = md[:md.index("## 0.")] if "## 0." in md else md
        assert "THE REGISTERED GATES DO NOT PASS" in head, \
            "the registered placebo fails and the file does not lead with it"
        assert "`null_holds` is **false**" in head.lower() or "null_holds` is **false**" in head, \
            "the banner must name null_holds explicitly"
        assert "NULL DOES NOT HOLD" in md
    elif nh is True:
        assert "THE REGISTERED GATES DO NOT PASS" not in md or "H1" in md


def test_the_document_agrees_with_the_evidentiary_bar(md, registered):
    """H1 may not be reported as holding while any leg of the bar fails."""
    legs = registered["legs"]
    if legs and not all(legs.values()):
        assert registered["retier"] in md, "the file must carry H1's re-tier verdict verbatim"
        assert "DIAGNOSTIC ON A DOWNGRADED HYPOTHESIS" in md, \
            "the hold-out section must be labelled as a diagnostic, not a result"


def test_its_own_placebo_is_labelled_as_not_the_registered_one(md):
    """The module's own shuffle spans zero and the registered placebo does not. That disagreement
    is a fact about the diagnostic, and the file must not let a reader mistake one for the other."""
    assert "DIAGNOSTIC, NOT THE REGISTERED PLACEBO" in md
    assert "This is not the placebo the project gates on" in md


def test_the_verdict_is_computed_from_the_registered_files_only(registered):
    """framework_sound must never be true while a registered gate is false, whatever this
    module's own checks say. Its own placebo currently PASSES, so a module grading itself
    would still be reporting 'sound' here."""
    if not JSON_OUT.exists():
        pytest.skip("data/evaluation.json not generated")
    r = json.loads(JSON_OUT.read_text())
    gates_bad = registered["null_holds"] is False or (registered["legs"] and not all(registered["legs"].values()))
    if gates_bad:
        assert r["overall"]["framework_sound"] is False, \
            "framework_sound is true while a registered gate fails"
    assert r["placebo"].get("gates") is False, "the module's own placebo must declare that it gates nothing"
    assert "registered_gates" in r, "the report must carry the registered gates it read"


def test_the_banner_is_regenerated_not_hand_added():
    """The defect was a hand-added banner on a machine-generated file. The generator must emit it."""
    src = (ROOT / "src" / "evaluate.py").read_text()
    assert "def _status_banner(" in src
    assert "THE REGISTERED GATES DO NOT PASS" in src, "the banner text must live in the generator"
    body = src[src.index("def _write_md("):]
    assert body.index("_status_banner(r)") < body.index("Generated by `src/evaluate.py`"), \
        "the status must precede the generated-by line, i.e. be the first thing read"

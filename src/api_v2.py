    @app.get("/api/engine_read")
    def api_engine_read(id: str, as_of: str | None = None, weighting: str | None = None):
        """The state-vector read for a corpus event, point-in-time (engine.read; PATH Step 7)."""
        import engine.read as R
        import engine.similarity as S
        c = _corpus()
        if id not in c.by_id:
            raise HTTPException(404, f"unknown event {id}")
        menu = S.load_menu()["items"]
        w = next((m for m in menu if m["id"] == weighting), menu[0])
        r = R.read(c, c.by_id[id], as_of=as_of, weighting=w)
        r["weighting_note"] = f"menu item {w['id']} (registered menu; the walk's Hedge weights are in data/walk_forward/weights.jsonl)"
        return r

    @app.get("/api/walk/summary")
    def api_walk_summary():
        s = _json(DATA / "walk_forward" / "summary.json")
        if not s:
            raise HTTPException(404, "no walk summary; run python3 src/walk.py")
        # Brief A-1 (2026-09-02): pass the published summary through WHOLE -- no key whitelist, so the endpoint can never
        # drift from summary.json again (the earlier list read `leakage` / `rps_vs`, which the file never had). The only
        # thing dropped is each tier task's per-item table (`items_vs_climatology`), which is large; /api/walk/read has it.
        tiers = {}
        for t, d in (s.get("tiers") or {}).items():
            td = dict(d)
            for task in ("G", "P", "M"):
                if isinstance(td.get(task), dict) and "items_vs_climatology" in td[task]:
                    td[task] = {k: v for k, v in td[task].items() if k != "items_vs_climatology"}
            tiers[t] = td
        return {k: v for k, v in s.items() if k != "tiers"} | {"tiers": tiers}

    @app.get("/api/record")
    def api_record():
        """NORTH_STAR §7 Record bar (Brief A-14): n events, n sealed reads, the §7 verdict statuses verbatim, last run_id, audit status."""
        import audit_ies90 as AU

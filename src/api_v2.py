    @app.get("/api/events")
    def api_events(q: str = "", limit: int = 30):
        conn = sqlite3.connect(DB)
        like = f"%{q.strip()}%"
        rows = conn.execute(
            "SELECT DISTINCT e.event_id, e.event_date, e.type, e.title FROM events e "
            "LEFT JOIN event_entities ee ON ee.event_id=e.event_id "
            "WHERE e.title LIKE ? OR e.event_id LIKE ? OR e.type LIKE ? OR e.event_date LIKE ? OR ee.entity_id LIKE ? "
            "ORDER BY e.event_date DESC LIMIT ?", (like, like, like, like, like, limit)).fetchall()
        conn.close()
        return [{"event_id": r[0], "date": r[1], "type": r[2], "title": r[3]} for r in rows]

